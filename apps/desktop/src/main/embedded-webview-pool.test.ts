import { EventEmitter } from "node:events";
import { describe, expect, it, vi } from "vitest";

const ipc = vi.hoisted(() => ({ handlers: new Map<string, (...args: any[]) => any>(), listeners: new Map<string, (...args: any[]) => any>(), owner: null as any, openExternal: vi.fn() }));
vi.mock("electron", () => ({
  BrowserWindow: { fromWebContents: () => ipc.owner },
  ipcMain: { handle: (name: string, fn: (...args: any[]) => any) => ipc.handlers.set(name, fn), on: (name: string, fn: (...args: any[]) => any) => ipc.listeners.set(name, fn) },
  shell: { openExternal: ipc.openExternal },
}));
import { clearEmbeddedWebviews, installEmbeddedWebviewHost, setupEmbeddedWebviewExperiment } from "./embedded-webview-experiment";

describe("embedded issue warm pool", () => {
  it("waits for the guest to apply presentation before enabling its shell header", async () => {
    const contents = Object.assign(new EventEmitter(), { send: vi.fn() });
    const owner = Object.assign(new EventEmitter(), { webContents: contents, isDestroyed: () => false });
    const guest = Object.assign(new EventEmitter(), { send: vi.fn(), isDestroyed: () => false, close: vi.fn(), setWindowOpenHandler: vi.fn(), debugger: { isAttached: () => true, detach: vi.fn(), sendCommand: vi.fn(async () => {}) } });
    ipc.owner = owner;
    setupEmbeddedWebviewExperiment({ isMain: () => true, userId: () => "user", workspaceSlug: () => "team", locale: () => "en", rendererUrl: "http://localhost:5173/" });
    installEmbeddedWebviewHost(owner as never);
    const event = { sender: contents };
    const ticket = ipc.handlers.get("embedded-guest:prepare")!(event, { userId: "user", workspaceId: "ws", issueId: "one", path: "/team/issues/one", title: "one" });
    contents.emit("will-attach-webview", { preventDefault: vi.fn() }, {}, { src: ticket.url });
    contents.emit("did-attach-webview", {}, guest);
    await ipc.handlers.get("embedded-guest:activate")!(event, ticket.token);
    const command = ipc.handlers.get("embedded-guest:header-command")!;
    const pending = ipc.handlers.get("embedded-guest:presentation")!(event, ticket.token, { surface: "main", shellHeader: true });
    expect(command(event, { token: ticket.token, command: "toggle-sidebar" })).toBe(false);
    const sent = guest.send.mock.calls.find(([channel]) => channel === "embedded-guest:presentation")?.[1];
    expect(sent).toMatchObject({ surface: "main", shellHeader: true, presentationRequestId: expect.any(Number) });
    ipc.listeners.get("embedded-guest:presentation-ack")!({ sender: {} }, sent.presentationRequestId);
    expect(command(event, { token: ticket.token, command: "toggle-sidebar" })).toBe(false);
    ipc.listeners.get("embedded-guest:presentation-ack")!({ sender: guest }, sent.presentationRequestId);
    expect(await pending).toBe(true);
    expect(command(event, { token: ticket.token, command: "toggle-sidebar" })).toBe(true);
    const refreshing = command(event, { token: ticket.token, command: "refresh-issue" });
    const refreshId = guest.send.mock.calls.at(-1)?.[1].refreshRequestId;
    ipc.listeners.get("embedded-guest:refresh-ack")!({ sender: {} }, { requestId: refreshId, success: false });
    ipc.listeners.get("embedded-guest:refresh-ack")!({ sender: guest }, { requestId: refreshId, success: true });
    expect(await refreshing).toBe(true);
    const old = ipc.handlers.get("embedded-guest:presentation")!(event, ticket.token, { surface: "main", shellHeader: true });
    expect(command(event, { token: ticket.token, command: "toggle-sidebar" })).toBe(true);
    const oldId = guest.send.mock.calls.at(-1)?.[1].presentationRequestId;
    const newer = ipc.handlers.get("embedded-guest:presentation")!(event, ticket.token, { surface: "dock" });
    const newId = guest.send.mock.calls.at(-1)?.[1].presentationRequestId;
    ipc.listeners.get("embedded-guest:presentation-ack")!({ sender: guest }, oldId);
    expect(await old).toBe(false);
    expect(command(event, { token: ticket.token, command: "toggle-sidebar" })).toBe(false);
    ipc.listeners.get("embedded-guest:presentation-ack")!({ sender: guest }, newId);
    expect(await newer).toBe(true);
    expect(command(event, { token: ticket.token, command: "toggle-sidebar" })).toBe(false);
    clearEmbeddedWebviews(owner as never);
  });
  it("only dispatches header commands to the active main issue with a shell header", async () => {
    const contents = Object.assign(new EventEmitter(), { send: vi.fn() });
    const owner = Object.assign(new EventEmitter(), { webContents: contents, isDestroyed: () => false });
    const makeGuest = () => Object.assign(new EventEmitter(), { send: vi.fn(), isDestroyed: () => false, close: vi.fn(), setWindowOpenHandler: vi.fn(), debugger: { isAttached: () => true, detach: vi.fn(), sendCommand: vi.fn(async () => {}) } });
    ipc.owner = owner;
    let currentUser = "user", currentWorkspace = "team";
    setupEmbeddedWebviewExperiment({ isMain: () => true, userId: () => currentUser, workspaceSlug: () => currentWorkspace, locale: () => "en", rendererUrl: "http://localhost:5173/" });
    installEmbeddedWebviewHost(owner as never);
    const event = { sender: contents };
    const create = (id: string) => {
      const ticket = ipc.handlers.get("embedded-guest:prepare")!(event, { userId: "user", workspaceId: "ws", issueId: id, path: `/team/issues/${id}`, title: id });
      const guest = makeGuest();
      contents.emit("will-attach-webview", { preventDefault: vi.fn() }, {}, { src: ticket.url });
      contents.emit("did-attach-webview", {}, guest);
      return { ticket, guest };
    };
    const first = create("one"), second = create("two");
    const activate = ipc.handlers.get("embedded-guest:activate")!;
    const present = ipc.handlers.get("embedded-guest:presentation")!;
    const command = ipc.handlers.get("embedded-guest:header-command")!;
    const presentAndAck = async (item: typeof first, value: unknown) => {
      const pending = present(event, item.ticket.token, value);
      const sent = item.guest.send.mock.calls.filter(([channel]) => channel === "embedded-guest:presentation").at(-1)?.[1];
      ipc.listeners.get("embedded-guest:presentation-ack")!({ sender: item.guest }, sent.presentationRequestId);
      return pending;
    };
    await activate(event, first.ticket.token);
    expect(command(event, { token: first.ticket.token, command: "toggle-sidebar" })).toBe(false);
    expect(await presentAndAck(first, { surface: "main", shellHeader: true })).toBe(true);
    expect(command(event, { token: first.ticket.token, command: "toggle-sidebar" })).toBe(true);
    expect(first.guest.send).toHaveBeenCalledWith("embedded-guest:header-command", { token: first.ticket.token, command: "toggle-sidebar" });
    const state = ipc.listeners.get("embedded-guest:header-state")!;
    state({ sender: first.guest }, { sidebarOpen: true });
    expect(contents.send).toHaveBeenCalledWith("embedded-guest:header-state", { token: first.ticket.token, sidebarOpen: true });
    await activate(event, second.ticket.token);
    expect(command(event, { token: first.ticket.token, command: "toggle-sidebar" })).toBe(false);
    contents.send.mockClear();
    state({ sender: first.guest }, { sidebarOpen: false });
    expect(contents.send).not.toHaveBeenCalled();
    expect(await presentAndAck(second, { surface: "dock" })).toBe(true);
    expect(command(event, { token: second.ticket.token, command: "toggle-sidebar" })).toBe(false);
    state({ sender: second.guest }, { sidebarOpen: true });
    expect(contents.send).not.toHaveBeenCalled();
    expect(await presentAndAck(second, { surface: "main", shellHeader: true })).toBe(true);
    expect(command(event, { token: second.ticket.token, command: "jump-to-run", taskId: "task-1" })).toBe(true);
    expect(second.guest.send).toHaveBeenCalledWith("embedded-guest:header-command", { token: second.ticket.token, command: "jump-to-run", taskId: "task-1" });
    currentWorkspace = "other";
    expect(command(event, { token: second.ticket.token, command: "toggle-sidebar" })).toBe(false);
    state({ sender: second.guest }, { sidebarOpen: true });
    expect(contents.send).not.toHaveBeenCalled();
    currentWorkspace = "team"; currentUser = "other";
    expect(command(event, { token: second.ticket.token, command: "toggle-sidebar" })).toBe(false);
    state({ sender: second.guest }, { sidebarOpen: true });
    expect(contents.send).not.toHaveBeenCalled();
    clearEmbeddedWebviews(owner as never);
  });
  it("allows only the packaged renderer file for a guest", () => {
    const contents = Object.assign(new EventEmitter(), { send: vi.fn() });
    const owner = Object.assign(new EventEmitter(), { webContents: contents, isDestroyed: () => false });
    const guest = Object.assign(new EventEmitter(), { send: vi.fn(), isDestroyed: () => false, close: vi.fn(), setWindowOpenHandler: vi.fn(), debugger: { isAttached: () => false } });
    ipc.owner = owner;
    setupEmbeddedWebviewExperiment({ isMain: () => true, userId: () => "user", workspaceSlug: () => "team", locale: () => "en", rendererUrl: "file:///C:/app/renderer/index.html" });
    installEmbeddedWebviewHost(owner as never);
    const pool = ipc.handlers.get("embedded-pool:prepare")!({ sender: contents }, { userId: "user", workspaceId: "ws", workspaceSlug: "team" });
    const attach = { preventDefault: vi.fn() };
    contents.emit("will-attach-webview", attach, {}, { src: pool.url });
    expect(attach.preventDefault).not.toHaveBeenCalled();
    contents.emit("did-attach-webview", {}, guest);
    const windowOpen = guest.setWindowOpenHandler.mock.calls[0][0];
    ipc.openExternal.mockClear();
    expect(windowOpen({ url: "https://project.feishu.cn/example" })).toEqual({ action: "deny" });
    expect(ipc.openExternal).toHaveBeenCalledWith("https://project.feishu.cn/example");
    ipc.openExternal.mockClear();
    expect(windowOpen({ url: "file:///C:/secret" })).toEqual({ action: "deny" });
    expect(ipc.openExternal).not.toHaveBeenCalled();
    const navigation = { preventDefault: vi.fn() };
    guest.emit("will-navigate", navigation, "file:///C:/elsewhere/other.html");
    expect(navigation.preventDefault).toHaveBeenCalled();
    clearEmbeddedWebviews(owner as never);
  });
  it("assigns a ready container only once and only to its original workspace", () => {
    const contents = Object.assign(new EventEmitter(), { send: vi.fn() });
    const owner = Object.assign(new EventEmitter(), { webContents: contents, isDestroyed: () => false });
    const guest = Object.assign(new EventEmitter(), { send: vi.fn(), isDestroyed: () => false, close: vi.fn(), setWindowOpenHandler: vi.fn(), debugger: { isAttached: () => false } });
    ipc.owner = owner;
    setupEmbeddedWebviewExperiment({ isMain: () => true, userId: () => "user", workspaceSlug: () => "team", locale: () => "en", rendererUrl: "http://localhost:5173/" });
    installEmbeddedWebviewHost(owner as never);
    const event = { sender: contents };
    const pool = ipc.handlers.get("embedded-pool:prepare")!(event, { userId: "user", workspaceId: "ws", workspaceSlug: "team" });
    expect(pool).toBeTruthy();
    const attach = { preventDefault: vi.fn() };
    contents.emit("will-attach-webview", attach, {}, { src: pool.url });
    expect(attach.preventDefault).not.toHaveBeenCalled();
    contents.emit("did-attach-webview", {}, guest);
    const request = { userId: "user", workspaceId: "ws", issueId: "issue-1", path: "/team/issues/issue-1", title: "Issue" };
    expect(ipc.handlers.get("embedded-pool:assign")!(event, pool.token, request)).toBe(false);
    ipc.listeners.get("embedded-pool:ready")!({ sender: guest });
    expect(ipc.handlers.get("embedded-pool:assign")!(event, pool.token, { ...request, workspaceId: "other" })).toBe(false);
    expect(ipc.handlers.get("embedded-pool:assign")!(event, pool.token, request)).toBe(true);
    expect(guest.send).toHaveBeenCalledWith("embedded-pool:assigned", expect.objectContaining({ issueId: "issue-1" }));
    expect(ipc.handlers.get("embedded-pool:assign")!(event, pool.token, request)).toBe(false);
    clearEmbeddedWebviews(owner as never);
  });
});
